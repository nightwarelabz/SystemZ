#!/usr/bin/env python3
"""Embed the checked-in RGB565 artwork. Build-time stdlib only; no decoder in boot."""
from pathlib import Path
import sys

root = Path(__file__).resolve().parent
data = (root / 'assets/telepathy.rgb565').read_bytes()
if len(data) != 384 * 128 * 2:
    raise SystemExit('boot artwork must be 384x128 little-endian RGB565')
out = Path(sys.argv[1])
out.parent.mkdir(parents=True, exist_ok=True)
with out.open('w') as f:
    f.write('/* Generated by boot/embed.py; source: boot/assets/telepathy.rgb565. */\n')
    f.write('static const unsigned char sz_art[] = {\n')
    for i in range(0, len(data), 24):
        f.write(','.join(str(x) for x in data[i:i + 24]) + ',\n')
    f.write('};\n')
